import { describe, it, expect } from 'vitest';
import { parseFeedSheet, mergeFeed } from './feedSheet';
const rf = (n: string) => (n.includes('최진수') || n === '민서' ? '민서' : n.includes('산성') ? '산성농원' : '');
describe('그룹 사료 사용 읽기', () => {
  it('세로형', () => {
    const r = parseFeedSheet([['그룹 사료 사용'], ['농장명', '그룹명', '사용월', '사료명', '사용량(kg)'], ['민서(최진수)', '26-3', '2026-04', '윈맥스S트랜스', '3,162'], ['', '', '2026-05', '리더MF1호', 4299.443], ['피그팜', '26-1', '2026-05', '리더MF2호', 10], ['합계', '', '', '', 7471]], rf, 2026);
    expect(r).toEqual([['민서', '26-3', '2026-04', '윈맥스S트랜스', 3162], ['민서', '26-3', '2026-05', '리더MF1호', 4299.443]]);
  });
  it('가로형', () => {
    const r = parseFeedSheet([['농장', '그룹', '사료', '4월', '5월'], ['산성농원', '26-4차', '리더MF2호', 100, 200]], rf, 2026);
    expect(r).toEqual([['산성농원', '26-4', '2026-04', '리더MF2호', 100], ['산성농원', '26-4', '2026-05', '리더MF2호', 200]]);
  });
  it('나중 값 우선', () => {
    expect(mergeFeed([{ file: 'b', at: '2', rows: ['민서\t26-3\t2026-04\tx\t2'] }, { file: 'a', at: '1', rows: ['민서\t26-3\t2026-04\tx\t1'] }])).toEqual([['민서', '26-3', '2026-04', 'x', 2]]);
  });
});

describe('피그온 그룹 사료 사용(두 줄 머리, HTML 엑셀)', () => {
  it('품목명·중량 칸, 그룹 2026-002 → 26-2, 소계 제외', () => {
    const a = [['그룹 사료 사용'], ['소속1', '소속2', '소속3', '농장명', '저장위치', '그룹명', '기준월', '품목', '', '사용', ''], ['', '', '', '', '', '', '', '품목코드', '품목명', '수량', '중량'],
      ['팜스코', '비육', '3팀', '명임', 'B1', '명임-명임-2026-002', '202606', '1211', '리더MF 1호P(B)', '5940', '5940'],
      ['팜스코', '비육', '3팀', '명임', 'B1', '명임-명임-2026-002', '202606 소계', '', '', '', '5940']];
    expect(parseFeedSheet(a, (s) => (s === '명임' ? '명임' : ''))).toEqual([['명임', '26-2', '2026-06', '리더MF 1호P(B)', 5940]]);
  });
});
